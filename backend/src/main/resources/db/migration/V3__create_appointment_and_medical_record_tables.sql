CREATE TABLE appointment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    patient_id BIGINT NOT NULL,
    doctor_id BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    scheduled_start_at TIMESTAMP(6) NOT NULL,
    scheduled_end_at TIMESTAMP(6) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'SCHEDULED',
    reason VARCHAR(512) NOT NULL,
    scheduling_notes VARCHAR(1024),
    check_in_at TIMESTAMP(6),
    queue_position INTEGER,
    cancelled_at TIMESTAMP(6),
    cancellation_reason VARCHAR(512),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_user_id BIGINT,
    updated_by_user_id BIGINT,

    CONSTRAINT pk_appointment PRIMARY KEY (id),
    CONSTRAINT chk_appointment__time_range CHECK (scheduled_start_at < scheduled_end_at),
    CONSTRAINT chk_appointment__status CHECK (status IN (
        'SCHEDULED', 'CHECKED_IN', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED', 'NO_SHOW'
    )),
    CONSTRAINT chk_appointment__reason_not_blank CHECK (CHAR_LENGTH(TRIM(reason)) > 0),
    CONSTRAINT chk_appointment__queue_position_positive
        CHECK (queue_position IS NULL OR queue_position > 0),
    CONSTRAINT chk_appointment__cancelled_fields CHECK (
        (
            status = 'CANCELLED'
            AND cancelled_at IS NOT NULL
            AND cancellation_reason IS NOT NULL
        ) OR status <> 'CANCELLED'
    ),
    CONSTRAINT fk_appointment__patient FOREIGN KEY (patient_id)
        REFERENCES patient (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointment__doctor FOREIGN KEY (doctor_id)
        REFERENCES doctor (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointment__department FOREIGN KEY (department_id)
        REFERENCES department (id) ON DELETE RESTRICT,
    CONSTRAINT fk_appointment__created_by_user FOREIGN KEY (created_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL,
    CONSTRAINT fk_appointment__updated_by_user FOREIGN KEY (updated_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL
);

CREATE INDEX idx_appointment__doctor_start_status
    ON appointment (doctor_id, scheduled_start_at, status);
CREATE INDEX idx_appointment__patient_start
    ON appointment (patient_id, scheduled_start_at);
CREATE INDEX idx_appointment__department_start
    ON appointment (department_id, scheduled_start_at);
CREATE INDEX idx_appointment__status_start
    ON appointment (status, scheduled_start_at);
CREATE INDEX idx_appointment__doctor_queue
    ON appointment (doctor_id, queue_position);
CREATE INDEX idx_appointment__start_end
    ON appointment (scheduled_start_at, scheduled_end_at);

CREATE TABLE medical_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    patient_id BIGINT NOT NULL,
    doctor_id BIGINT NOT NULL,
    appointment_id BIGINT,
    encounter_at TIMESTAMP(6) NOT NULL,
    symptoms TEXT,
    clinical_notes TEXT NOT NULL,
    patient_visible BOOLEAN NOT NULL DEFAULT FALSE,
    released_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_user_id BIGINT,
    updated_by_user_id BIGINT,

    CONSTRAINT pk_medical_record PRIMARY KEY (id),
    CONSTRAINT chk_medical_record__clinical_notes_not_blank
        CHECK (CHAR_LENGTH(TRIM(clinical_notes)) > 0),
    CONSTRAINT chk_medical_record__release_fields CHECK (
        (patient_visible = TRUE AND released_at IS NOT NULL)
        OR patient_visible = FALSE
    ),
    CONSTRAINT fk_medical_record__patient FOREIGN KEY (patient_id)
        REFERENCES patient (id) ON DELETE RESTRICT,
    CONSTRAINT fk_medical_record__doctor FOREIGN KEY (doctor_id)
        REFERENCES doctor (id) ON DELETE RESTRICT,
    CONSTRAINT fk_medical_record__appointment FOREIGN KEY (appointment_id)
        REFERENCES appointment (id) ON DELETE RESTRICT,
    CONSTRAINT fk_medical_record__created_by_user FOREIGN KEY (created_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL,
    CONSTRAINT fk_medical_record__updated_by_user FOREIGN KEY (updated_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL
);

CREATE INDEX idx_medical_record__patient_encounter
    ON medical_record (patient_id, encounter_at);
CREATE INDEX idx_medical_record__doctor_encounter
    ON medical_record (doctor_id, encounter_at);
CREATE INDEX idx_medical_record__appointment
    ON medical_record (appointment_id);
CREATE INDEX idx_medical_record__patient_visible
    ON medical_record (patient_id, patient_visible, released_at);

CREATE TABLE diagnosis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    medical_record_id BIGINT NOT NULL,
    code_system VARCHAR(64),
    diagnosis_code VARCHAR(64),
    description VARCHAR(512) NOT NULL,
    diagnosis_type VARCHAR(16) NOT NULL DEFAULT 'SECONDARY',
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_user_id BIGINT,
    updated_by_user_id BIGINT,

    CONSTRAINT pk_diagnosis PRIMARY KEY (id),
    CONSTRAINT chk_diagnosis__description_not_blank
        CHECK (CHAR_LENGTH(TRIM(description)) > 0),
    CONSTRAINT chk_diagnosis__type
        CHECK (diagnosis_type IN ('PRIMARY', 'SECONDARY')),
    CONSTRAINT chk_diagnosis__code_pair CHECK (
        (code_system IS NULL AND diagnosis_code IS NULL)
        OR (code_system IS NOT NULL AND diagnosis_code IS NOT NULL)
    ),
    CONSTRAINT fk_diagnosis__medical_record FOREIGN KEY (medical_record_id)
        REFERENCES medical_record (id) ON DELETE RESTRICT,
    CONSTRAINT fk_diagnosis__created_by_user FOREIGN KEY (created_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL,
    CONSTRAINT fk_diagnosis__updated_by_user FOREIGN KEY (updated_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL
);

CREATE INDEX idx_diagnosis__medical_record
    ON diagnosis (medical_record_id);
CREATE INDEX idx_diagnosis__code
    ON diagnosis (code_system, diagnosis_code);

CREATE TABLE vital_sign (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    medical_record_id BIGINT NOT NULL,
    recorded_at TIMESTAMP(6) NOT NULL,
    temperature_celsius DECIMAL(5,2),
    systolic_bp SMALLINT,
    diastolic_bp SMALLINT,
    heart_rate SMALLINT,
    respiratory_rate SMALLINT,
    oxygen_saturation DECIMAL(5,2),
    weight_kg DECIMAL(7,2),
    height_cm DECIMAL(7,2),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_user_id BIGINT,
    updated_by_user_id BIGINT,

    CONSTRAINT pk_vital_sign PRIMARY KEY (id),
    CONSTRAINT chk_vital_sign__temperature CHECK (
        temperature_celsius IS NULL OR temperature_celsius BETWEEN 25.00 AND 50.00
    ),
    CONSTRAINT chk_vital_sign__systolic CHECK (
        systolic_bp IS NULL OR systolic_bp BETWEEN 40 AND 300
    ),
    CONSTRAINT chk_vital_sign__diastolic CHECK (
        diastolic_bp IS NULL OR diastolic_bp BETWEEN 20 AND 200
    ),
    CONSTRAINT chk_vital_sign__blood_pressure_pair CHECK (
        (systolic_bp IS NULL AND diastolic_bp IS NULL)
        OR (
            systolic_bp IS NOT NULL
            AND diastolic_bp IS NOT NULL
            AND systolic_bp > diastolic_bp
        )
    ),
    CONSTRAINT chk_vital_sign__heart_rate CHECK (
        heart_rate IS NULL OR heart_rate BETWEEN 20 AND 300
    ),
    CONSTRAINT chk_vital_sign__respiratory_rate CHECK (
        respiratory_rate IS NULL OR respiratory_rate BETWEEN 4 AND 80
    ),
    CONSTRAINT chk_vital_sign__oxygen_saturation CHECK (
        oxygen_saturation IS NULL OR oxygen_saturation BETWEEN 0.00 AND 100.00
    ),
    CONSTRAINT chk_vital_sign__weight CHECK (weight_kg IS NULL OR weight_kg > 0),
    CONSTRAINT chk_vital_sign__height CHECK (height_cm IS NULL OR height_cm > 0),
    CONSTRAINT fk_vital_sign__medical_record FOREIGN KEY (medical_record_id)
        REFERENCES medical_record (id) ON DELETE RESTRICT,
    CONSTRAINT fk_vital_sign__created_by_user FOREIGN KEY (created_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL,
    CONSTRAINT fk_vital_sign__updated_by_user FOREIGN KEY (updated_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL
);

CREATE INDEX idx_vital_sign__medical_record_recorded
    ON vital_sign (medical_record_id, recorded_at);
