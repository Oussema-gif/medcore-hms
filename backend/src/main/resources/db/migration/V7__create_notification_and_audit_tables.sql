CREATE TABLE notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_account_id BIGINT NOT NULL,
    notification_type VARCHAR(64) NOT NULL,
    title VARCHAR(256) NOT NULL,
    body VARCHAR(2048) NOT NULL,
    resource_type VARCHAR(64),
    resource_id BIGINT,
    read_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_notification PRIMARY KEY (id),
    CONSTRAINT chk_notification__type_not_blank
        CHECK (CHAR_LENGTH(TRIM(notification_type)) > 0),
    CONSTRAINT chk_notification__title_not_blank
        CHECK (CHAR_LENGTH(TRIM(title)) > 0),
    CONSTRAINT chk_notification__body_not_blank
        CHECK (CHAR_LENGTH(TRIM(body)) > 0),
    CONSTRAINT fk_notification__user_account
        FOREIGN KEY (user_account_id)
        REFERENCES user_account (id)
        ON DELETE RESTRICT
);

CREATE INDEX idx_notification__user_read_created
    ON notification (user_account_id, read_at, created_at);

CREATE INDEX idx_notification__resource
    ON notification (resource_type, resource_id);

CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    actor_user_id BIGINT,
    action VARCHAR(128) NOT NULL,
    entity_type VARCHAR(128),
    entity_id BIGINT,
    outcome VARCHAR(16) NOT NULL,
    source_ip VARCHAR(45),
    request_id VARCHAR(128),
    metadata_json JSON,
    occurred_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_audit_log PRIMARY KEY (id),
    CONSTRAINT chk_audit_log__action_not_blank
        CHECK (CHAR_LENGTH(TRIM(action)) > 0),
    CONSTRAINT chk_audit_log__entity_pair CHECK (
        (entity_type IS NULL AND entity_id IS NULL)
        OR (entity_type IS NOT NULL AND entity_id IS NOT NULL)
    ),
    CONSTRAINT chk_audit_log__outcome
        CHECK (outcome IN ('SUCCESS', 'FAILURE', 'DENIED')),
    CONSTRAINT fk_audit_log__actor_user
        FOREIGN KEY (actor_user_id)
        REFERENCES user_account (id)
        ON DELETE SET NULL
);

CREATE INDEX idx_audit_log__occurred_at
    ON audit_log (occurred_at);

CREATE INDEX idx_audit_log__actor_occurred
    ON audit_log (actor_user_id, occurred_at);

CREATE INDEX idx_audit_log__entity_occurred
    ON audit_log (entity_type, entity_id, occurred_at);

CREATE INDEX idx_audit_log__action_outcome_occurred
    ON audit_log (action, outcome, occurred_at);

CREATE INDEX idx_audit_log__request_id
    ON audit_log (request_id);
