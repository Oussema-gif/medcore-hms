CREATE TABLE department (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    code VARCHAR(32) NOT NULL,
    name VARCHAR(128) NOT NULL,
    description VARCHAR(512),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    deleted_at TIMESTAMP(6),
    deleted_by_user_id BIGINT,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_user_id BIGINT,
    updated_by_user_id BIGINT,

    CONSTRAINT pk_department PRIMARY KEY (id),
    CONSTRAINT uk_department__code UNIQUE (code),
    CONSTRAINT uk_department__name UNIQUE (name),
    CONSTRAINT chk_department__code_not_blank CHECK (CHAR_LENGTH(TRIM(code)) > 0),
    CONSTRAINT chk_department__name_not_blank CHECK (CHAR_LENGTH(TRIM(name)) > 0),
    CONSTRAINT fk_department__deleted_by_user FOREIGN KEY (deleted_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL,
    CONSTRAINT fk_department__created_by_user FOREIGN KEY (created_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL,
    CONSTRAINT fk_department__updated_by_user FOREIGN KEY (updated_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL
);

CREATE INDEX idx_department__active ON department (active);
CREATE INDEX idx_department__deleted_at ON department (deleted_at);

CREATE TABLE doctor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_account_id BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    professional_registration_number VARCHAR(64) NOT NULL,
    first_name VARCHAR(128) NOT NULL,
    last_name VARCHAR(128) NOT NULL,
    specialty VARCHAR(256),
    phone_number VARCHAR(32),
    email VARCHAR(254),
    consultation_duration_minutes INTEGER NOT NULL DEFAULT 15,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_user_id BIGINT,
    updated_by_user_id BIGINT,

    CONSTRAINT pk_doctor PRIMARY KEY (id),
    CONSTRAINT uk_doctor__user_account UNIQUE (user_account_id),
    CONSTRAINT uk_doctor__registration_number UNIQUE (professional_registration_number),
    CONSTRAINT chk_doctor__first_name_not_blank CHECK (CHAR_LENGTH(TRIM(first_name)) > 0),
    CONSTRAINT chk_doctor__last_name_not_blank CHECK (CHAR_LENGTH(TRIM(last_name)) > 0),
    CONSTRAINT chk_doctor__consultation_duration_positive CHECK (consultation_duration_minutes > 0),
    CONSTRAINT fk_doctor__user_account FOREIGN KEY (user_account_id)
        REFERENCES user_account (id) ON DELETE RESTRICT,
    CONSTRAINT fk_doctor__department FOREIGN KEY (department_id)
        REFERENCES department (id) ON DELETE RESTRICT,
    CONSTRAINT fk_doctor__created_by_user FOREIGN KEY (created_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL,
    CONSTRAINT fk_doctor__updated_by_user FOREIGN KEY (updated_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL
);

CREATE INDEX idx_doctor__department_active ON doctor (department_id, active);
CREATE INDEX idx_doctor__name ON doctor (last_name, first_name);

CREATE TABLE doctor_availability (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    doctor_id BIGINT NOT NULL,
    day_of_week SMALLINT NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    effective_from DATE NOT NULL,
    effective_until DATE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_user_id BIGINT,
    updated_by_user_id BIGINT,

    CONSTRAINT pk_doctor_availability PRIMARY KEY (id),
    CONSTRAINT chk_doctor_availability__day_of_week CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT chk_doctor_availability__time_range CHECK (start_time < end_time),
    CONSTRAINT chk_doctor_availability__effective_range CHECK (
        effective_until IS NULL OR effective_from <= effective_until
    ),
    CONSTRAINT fk_doctor_availability__doctor FOREIGN KEY (doctor_id)
        REFERENCES doctor (id) ON DELETE RESTRICT,
    CONSTRAINT fk_doctor_availability__created_by_user FOREIGN KEY (created_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL,
    CONSTRAINT fk_doctor_availability__updated_by_user FOREIGN KEY (updated_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL
);

CREATE INDEX idx_doctor_availability__doctor_day
    ON doctor_availability (doctor_id, day_of_week, active);

CREATE INDEX idx_doctor_availability__effective
    ON doctor_availability (effective_from, effective_until);

CREATE TABLE patient (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_account_id BIGINT,
    medical_record_number VARCHAR(32) NOT NULL,
    first_name VARCHAR(128) NOT NULL,
    last_name VARCHAR(128) NOT NULL,
    date_of_birth DATE NOT NULL,
    sex VARCHAR(16) NOT NULL,
    email VARCHAR(254),
    phone_number VARCHAR(32),
    address_line1 VARCHAR(256),
    address_line2 VARCHAR(256),
    city VARCHAR(128),
    state VARCHAR(128),
    postal_code VARCHAR(32),
    country VARCHAR(128),
    emergency_contact_name VARCHAR(256),
    emergency_contact_phone VARCHAR(32),
    blood_group VARCHAR(8),
    allergies VARCHAR(1024),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    deleted_at TIMESTAMP(6),
    deleted_by_user_id BIGINT,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_user_id BIGINT,
    updated_by_user_id BIGINT,

    CONSTRAINT pk_patient PRIMARY KEY (id),
    CONSTRAINT uk_patient__medical_record_number UNIQUE (medical_record_number),
    CONSTRAINT uk_patient__user_account UNIQUE (user_account_id),
    CONSTRAINT chk_patient__first_name_not_blank CHECK (CHAR_LENGTH(TRIM(first_name)) > 0),
    CONSTRAINT chk_patient__last_name_not_blank CHECK (CHAR_LENGTH(TRIM(last_name)) > 0),
    CONSTRAINT chk_patient__sex CHECK (sex IN ('MALE', 'FEMALE', 'OTHER', 'UNKNOWN')),
    CONSTRAINT chk_patient__blood_group CHECK (
        blood_group IS NULL OR blood_group IN (
            'A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-'
        )
    ),
    CONSTRAINT fk_patient__user_account FOREIGN KEY (user_account_id)
        REFERENCES user_account (id) ON DELETE SET NULL,
    CONSTRAINT fk_patient__deleted_by_user FOREIGN KEY (deleted_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL,
    CONSTRAINT fk_patient__created_by_user FOREIGN KEY (created_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL,
    CONSTRAINT fk_patient__updated_by_user FOREIGN KEY (updated_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL
);

CREATE INDEX idx_patient__name ON patient (last_name, first_name);
CREATE INDEX idx_patient__contact ON patient (phone_number, email);
CREATE INDEX idx_patient__active_deleted ON patient (active, deleted_at);
