CREATE TABLE medicine (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    medicine_code VARCHAR(64) NOT NULL,
    name VARCHAR(256) NOT NULL,
    generic_name VARCHAR(256),
    dosage_form VARCHAR(64) NOT NULL,
    strength VARCHAR(128),
    unit VARCHAR(32) NOT NULL,
    reorder_level DECIMAL(19,4) NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    deleted_at TIMESTAMP(6),
    deleted_by_user_id BIGINT,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_user_id BIGINT,
    updated_by_user_id BIGINT,
    CONSTRAINT pk_medicine PRIMARY KEY (id),
    CONSTRAINT uk_medicine__medicine_code UNIQUE (medicine_code),
    CONSTRAINT chk_medicine__code_not_blank CHECK (CHAR_LENGTH(TRIM(medicine_code)) > 0),
    CONSTRAINT chk_medicine__name_not_blank CHECK (CHAR_LENGTH(TRIM(name)) > 0),
    CONSTRAINT chk_medicine__dosage_form_not_blank CHECK (CHAR_LENGTH(TRIM(dosage_form)) > 0),
    CONSTRAINT chk_medicine__unit_not_blank CHECK (CHAR_LENGTH(TRIM(unit)) > 0),
    CONSTRAINT chk_medicine__reorder_level_nonnegative CHECK (reorder_level >= 0),
    CONSTRAINT fk_medicine__deleted_by_user FOREIGN KEY (deleted_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL,
    CONSTRAINT fk_medicine__created_by_user FOREIGN KEY (created_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL,
    CONSTRAINT fk_medicine__updated_by_user FOREIGN KEY (updated_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL
);

CREATE INDEX idx_medicine__active_name ON medicine (active, name);
CREATE INDEX idx_medicine__deleted_at ON medicine (deleted_at);

CREATE TABLE prescription (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    patient_id BIGINT NOT NULL,
    doctor_id BIGINT NOT NULL,
    appointment_id BIGINT,
    medical_record_id BIGINT,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    prescribed_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP(6),
    notes VARCHAR(2048),
    cancelled_at TIMESTAMP(6),
    cancellation_reason VARCHAR(512),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_user_id BIGINT,
    updated_by_user_id BIGINT,
    CONSTRAINT pk_prescription PRIMARY KEY (id),
    CONSTRAINT chk_prescription__status
        CHECK (status IN ('ACTIVE', 'DISPENSED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT chk_prescription__expiry_after_prescribed
        CHECK (expires_at IS NULL OR expires_at >= prescribed_at),
    CONSTRAINT chk_prescription__cancelled_fields CHECK (
        (status = 'CANCELLED' AND cancelled_at IS NOT NULL AND cancellation_reason IS NOT NULL)
        OR status <> 'CANCELLED'
    ),
    CONSTRAINT fk_prescription__patient FOREIGN KEY (patient_id)
        REFERENCES patient (id) ON DELETE RESTRICT,
    CONSTRAINT fk_prescription__doctor FOREIGN KEY (doctor_id)
        REFERENCES doctor (id) ON DELETE RESTRICT,
    CONSTRAINT fk_prescription__appointment FOREIGN KEY (appointment_id)
        REFERENCES appointment (id) ON DELETE RESTRICT,
    CONSTRAINT fk_prescription__medical_record FOREIGN KEY (medical_record_id)
        REFERENCES medical_record (id) ON DELETE RESTRICT,
    CONSTRAINT fk_prescription__created_by_user FOREIGN KEY (created_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL,
    CONSTRAINT fk_prescription__updated_by_user FOREIGN KEY (updated_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL
);

CREATE INDEX idx_prescription__patient_prescribed ON prescription (patient_id, prescribed_at);
CREATE INDEX idx_prescription__doctor_status_prescribed ON prescription (doctor_id, status, prescribed_at);
CREATE INDEX idx_prescription__status_expiry ON prescription (status, expires_at);
CREATE INDEX idx_prescription__appointment ON prescription (appointment_id);
CREATE INDEX idx_prescription__medical_record ON prescription (medical_record_id);

CREATE TABLE prescription_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    prescription_id BIGINT NOT NULL,
    medicine_id BIGINT NOT NULL,
    dosage VARCHAR(128) NOT NULL,
    route VARCHAR(64) NOT NULL,
    frequency VARCHAR(128) NOT NULL,
    duration_days INTEGER NOT NULL,
    quantity_prescribed DECIMAL(19,4) NOT NULL,
    instructions VARCHAR(2048),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_prescription_item PRIMARY KEY (id),
    CONSTRAINT chk_prescription_item__dosage_not_blank CHECK (CHAR_LENGTH(TRIM(dosage)) > 0),
    CONSTRAINT chk_prescription_item__route_not_blank CHECK (CHAR_LENGTH(TRIM(route)) > 0),
    CONSTRAINT chk_prescription_item__frequency_not_blank CHECK (CHAR_LENGTH(TRIM(frequency)) > 0),
    CONSTRAINT chk_prescription_item__duration_positive CHECK (duration_days > 0),
    CONSTRAINT chk_prescription_item__quantity_positive CHECK (quantity_prescribed > 0),
    CONSTRAINT fk_prescription_item__prescription FOREIGN KEY (prescription_id)
        REFERENCES prescription (id) ON DELETE RESTRICT,
    CONSTRAINT fk_prescription_item__medicine FOREIGN KEY (medicine_id)
        REFERENCES medicine (id) ON DELETE RESTRICT
);

CREATE INDEX idx_prescription_item__prescription ON prescription_item (prescription_id);
CREATE INDEX idx_prescription_item__medicine ON prescription_item (medicine_id);

CREATE TABLE inventory_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    medicine_id BIGINT NOT NULL,
    lot_number VARCHAR(128) NOT NULL,
    expiry_date DATE NOT NULL,
    received_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    initial_quantity DECIMAL(19,4) NOT NULL,
    quantity_on_hand DECIMAL(19,4) NOT NULL,
    unit_cost DECIMAL(19,4) NOT NULL,
    supplier_reference VARCHAR(256),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_user_id BIGINT,
    updated_by_user_id BIGINT,
    CONSTRAINT pk_inventory_batch PRIMARY KEY (id),
    CONSTRAINT uk_inventory_batch__medicine_lot UNIQUE (medicine_id, lot_number),
    CONSTRAINT chk_inventory_batch__lot_not_blank CHECK (CHAR_LENGTH(TRIM(lot_number)) > 0),
    CONSTRAINT chk_inventory_batch__initial_quantity_nonnegative CHECK (initial_quantity >= 0),
    CONSTRAINT chk_inventory_batch__quantity_on_hand_nonnegative CHECK (quantity_on_hand >= 0),
    CONSTRAINT chk_inventory_batch__unit_cost_nonnegative CHECK (unit_cost >= 0),
    CONSTRAINT fk_inventory_batch__medicine FOREIGN KEY (medicine_id)
        REFERENCES medicine (id) ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_batch__created_by_user FOREIGN KEY (created_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL,
    CONSTRAINT fk_inventory_batch__updated_by_user FOREIGN KEY (updated_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL
);

CREATE INDEX idx_inventory_batch__medicine_active_expiry
    ON inventory_batch (medicine_id, active, expiry_date);
CREATE INDEX idx_inventory_batch__active_quantity_expiry
    ON inventory_batch (active, quantity_on_hand, expiry_date);

CREATE TABLE stock_movement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    inventory_batch_id BIGINT NOT NULL,
    movement_type VARCHAR(32) NOT NULL,
    quantity_delta DECIMAL(19,4) NOT NULL,
    quantity_after DECIMAL(19,4) NOT NULL,
    occurred_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reference_type VARCHAR(64),
    reference_id BIGINT,
    prescription_item_id BIGINT,
    reason VARCHAR(512),
    performed_by_user_id BIGINT NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_stock_movement PRIMARY KEY (id),
    CONSTRAINT chk_stock_movement__type CHECK (
        movement_type IN (
            'RECEIPT', 'ADJUSTMENT_IN', 'ADJUSTMENT_OUT',
            'DISPENSE', 'REVERSAL', 'EXPIRED_WRITE_OFF'
        )
    ),
    CONSTRAINT chk_stock_movement__delta_nonzero CHECK (quantity_delta <> 0),
    CONSTRAINT chk_stock_movement__quantity_after_nonnegative CHECK (quantity_after >= 0),
    CONSTRAINT fk_stock_movement__inventory_batch FOREIGN KEY (inventory_batch_id)
        REFERENCES inventory_batch (id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_movement__prescription_item FOREIGN KEY (prescription_item_id)
        REFERENCES prescription_item (id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_movement__performed_by_user FOREIGN KEY (performed_by_user_id)
        REFERENCES user_account (id) ON DELETE RESTRICT
);

CREATE INDEX idx_stock_movement__batch_occurred
    ON stock_movement (inventory_batch_id, occurred_at);
CREATE INDEX idx_stock_movement__reference
    ON stock_movement (reference_type, reference_id);
CREATE INDEX idx_stock_movement__prescription_item
    ON stock_movement (prescription_item_id);
CREATE INDEX idx_stock_movement__performed_by
    ON stock_movement (performed_by_user_id, occurred_at);