CREATE TABLE laboratory_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    patient_id BIGINT NOT NULL,
    ordering_doctor_id BIGINT NOT NULL,
    appointment_id BIGINT,
    medical_record_id BIGINT,
    priority VARCHAR(16) NOT NULL DEFAULT 'ROUTINE',
    status VARCHAR(32) NOT NULL DEFAULT 'REQUESTED',
    clinical_notes VARCHAR(2048),
    requested_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sample_collected_at TIMESTAMP(6),
    released_at TIMESTAMP(6),
    cancelled_at TIMESTAMP(6),
    cancellation_reason VARCHAR(512),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_user_id BIGINT,
    updated_by_user_id BIGINT,

    CONSTRAINT pk_laboratory_request PRIMARY KEY (id),
    CONSTRAINT chk_laboratory_request__priority
        CHECK (priority IN ('ROUTINE', 'URGENT', 'STAT')),
    CONSTRAINT chk_laboratory_request__status CHECK (status IN (
        'REQUESTED', 'SAMPLE_COLLECTED', 'IN_PROGRESS', 'RESULT_READY', 'RELEASED', 'CANCELLED'
    )),
    CONSTRAINT chk_laboratory_request__cancelled_fields CHECK (
        (
            status = 'CANCELLED'
            AND cancelled_at IS NOT NULL
            AND cancellation_reason IS NOT NULL
        ) OR status <> 'CANCELLED'
    ),
    CONSTRAINT chk_laboratory_request__sample_date CHECK (
        sample_collected_at IS NULL OR sample_collected_at >= requested_at
    ),
    CONSTRAINT chk_laboratory_request__release_date CHECK (
        released_at IS NULL OR released_at >= requested_at
    ),
    CONSTRAINT fk_laboratory_request__patient FOREIGN KEY (patient_id)
        REFERENCES patient (id) ON DELETE RESTRICT,
    CONSTRAINT fk_laboratory_request__ordering_doctor FOREIGN KEY (ordering_doctor_id)
        REFERENCES doctor (id) ON DELETE RESTRICT,
    CONSTRAINT fk_laboratory_request__appointment FOREIGN KEY (appointment_id)
        REFERENCES appointment (id) ON DELETE RESTRICT,
    CONSTRAINT fk_laboratory_request__medical_record FOREIGN KEY (medical_record_id)
        REFERENCES medical_record (id) ON DELETE RESTRICT,
    CONSTRAINT fk_laboratory_request__created_by_user FOREIGN KEY (created_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL,
    CONSTRAINT fk_laboratory_request__updated_by_user FOREIGN KEY (updated_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL
);

CREATE INDEX idx_laboratory_request__status_priority_requested
    ON laboratory_request (status, priority, requested_at);
CREATE INDEX idx_laboratory_request__patient_requested
    ON laboratory_request (patient_id, requested_at);
CREATE INDEX idx_laboratory_request__doctor_status_requested
    ON laboratory_request (ordering_doctor_id, status, requested_at);
CREATE INDEX idx_laboratory_request__appointment
    ON laboratory_request (appointment_id);
CREATE INDEX idx_laboratory_request__medical_record
    ON laboratory_request (medical_record_id);

CREATE TABLE laboratory_request_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    laboratory_request_id BIGINT NOT NULL,
    test_code VARCHAR(64) NOT NULL,
    test_name VARCHAR(256) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_laboratory_request_item PRIMARY KEY (id),
    CONSTRAINT uk_laboratory_request_item__request_test
        UNIQUE (laboratory_request_id, test_code),
    CONSTRAINT chk_laboratory_request_item__test_code_not_blank
        CHECK (CHAR_LENGTH(TRIM(test_code)) > 0),
    CONSTRAINT chk_laboratory_request_item__test_name_not_blank
        CHECK (CHAR_LENGTH(TRIM(test_name)) > 0),
    CONSTRAINT chk_laboratory_request_item__sort_order_positive
        CHECK (sort_order > 0),
    CONSTRAINT fk_laboratory_request_item__request
        FOREIGN KEY (laboratory_request_id)
        REFERENCES laboratory_request (id)
        ON DELETE RESTRICT
);

CREATE INDEX idx_laboratory_request_item__request_sort
    ON laboratory_request_item (laboratory_request_id, sort_order);

CREATE TABLE laboratory_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    laboratory_request_item_id BIGINT NOT NULL,
    result_value DECIMAL(19,6),
    result_text TEXT,
    unit VARCHAR(64),
    reference_range VARCHAR(256),
    interpretation VARCHAR(1024),
    recorded_by_user_id BIGINT NOT NULL,
    recorded_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    released_at TIMESTAMP(6),
    amended_from_result_id BIGINT,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_laboratory_result PRIMARY KEY (id),
    CONSTRAINT chk_laboratory_result__value_present CHECK (
        result_value IS NOT NULL
        OR (
            result_text IS NOT NULL
            AND CHAR_LENGTH(TRIM(result_text)) > 0
        )
    ),
    CONSTRAINT chk_laboratory_result__release_after_recorded CHECK (
        released_at IS NULL OR released_at >= recorded_at
    ),
    CONSTRAINT fk_laboratory_result__request_item FOREIGN KEY (laboratory_request_item_id)
        REFERENCES laboratory_request_item (id) ON DELETE RESTRICT,
    CONSTRAINT fk_laboratory_result__recorded_by_user FOREIGN KEY (recorded_by_user_id)
        REFERENCES user_account (id) ON DELETE RESTRICT,
    CONSTRAINT fk_laboratory_result__amended_from_result FOREIGN KEY (amended_from_result_id)
        REFERENCES laboratory_result (id) ON DELETE RESTRICT
);

CREATE INDEX idx_laboratory_result__request_item_recorded
    ON laboratory_result (laboratory_request_item_id, recorded_at);
CREATE INDEX idx_laboratory_result__released_at
    ON laboratory_result (released_at);
CREATE INDEX idx_laboratory_result__recorded_by
    ON laboratory_result (recorded_by_user_id);