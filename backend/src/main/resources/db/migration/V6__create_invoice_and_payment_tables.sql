CREATE TABLE invoice (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    invoice_number VARCHAR(64) NOT NULL,
    patient_id BIGINT NOT NULL,
    appointment_id BIGINT,
    status VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
    currency_code CHAR(3) NOT NULL,
    issue_date DATE NOT NULL,
    due_date DATE,
    subtotal_amount DECIMAL(19,4) NOT NULL DEFAULT 0.0000,
    discount_amount DECIMAL(19,4) NOT NULL DEFAULT 0.0000,
    tax_amount DECIMAL(19,4) NOT NULL DEFAULT 0.0000,
    total_amount DECIMAL(19,4) NOT NULL DEFAULT 0.0000,
    paid_amount DECIMAL(19,4) NOT NULL DEFAULT 0.0000,
    balance_amount DECIMAL(19,4) NOT NULL DEFAULT 0.0000,
    issued_at TIMESTAMP(6),
    voided_at TIMESTAMP(6),
    void_reason VARCHAR(512),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_user_id BIGINT,
    updated_by_user_id BIGINT,
    CONSTRAINT pk_invoice PRIMARY KEY (id),
    CONSTRAINT uk_invoice__invoice_number UNIQUE (invoice_number),
    CONSTRAINT chk_invoice__number_not_blank CHECK (CHAR_LENGTH(TRIM(invoice_number)) > 0),
    CONSTRAINT chk_invoice__status CHECK (
        status IN ('DRAFT', 'ISSUED', 'PARTIALLY_PAID', 'PAID', 'VOID', 'OVERDUE')
    ),
    CONSTRAINT chk_invoice__currency_code CHECK (
        CHAR_LENGTH(currency_code) = 3 AND currency_code = UPPER(currency_code)
    ),
    CONSTRAINT chk_invoice__due_date CHECK (due_date IS NULL OR due_date >= issue_date),
    CONSTRAINT chk_invoice__subtotal_nonnegative CHECK (subtotal_amount >= 0),
    CONSTRAINT chk_invoice__discount_nonnegative CHECK (discount_amount >= 0),
    CONSTRAINT chk_invoice__tax_nonnegative CHECK (tax_amount >= 0),
    CONSTRAINT chk_invoice__total_nonnegative CHECK (total_amount >= 0),
    CONSTRAINT chk_invoice__paid_nonnegative CHECK (paid_amount >= 0),
    CONSTRAINT chk_invoice__balance_nonnegative CHECK (balance_amount >= 0),
    CONSTRAINT chk_invoice__paid_not_above_total CHECK (paid_amount <= total_amount),
    CONSTRAINT chk_invoice__balance_not_above_total CHECK (balance_amount <= total_amount),
    CONSTRAINT chk_invoice__void_fields CHECK (
        (status = 'VOID' AND voided_at IS NOT NULL AND void_reason IS NOT NULL)
        OR status <> 'VOID'
    ),
    CONSTRAINT fk_invoice__patient FOREIGN KEY (patient_id)
        REFERENCES patient (id) ON DELETE RESTRICT,
    CONSTRAINT fk_invoice__appointment FOREIGN KEY (appointment_id)
        REFERENCES appointment (id) ON DELETE RESTRICT,
    CONSTRAINT fk_invoice__created_by_user FOREIGN KEY (created_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL,
    CONSTRAINT fk_invoice__updated_by_user FOREIGN KEY (updated_by_user_id)
        REFERENCES user_account (id) ON DELETE SET NULL
);

CREATE INDEX idx_invoice__patient_issue_date ON invoice (patient_id, issue_date);
CREATE INDEX idx_invoice__status_due_date ON invoice (status, due_date);
CREATE INDEX idx_invoice__balance_amount ON invoice (balance_amount);
CREATE INDEX idx_invoice__appointment ON invoice (appointment_id);

CREATE TABLE invoice_line_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    invoice_id BIGINT NOT NULL,
    line_number INTEGER NOT NULL,
    item_type VARCHAR(64) NOT NULL,
    description VARCHAR(512) NOT NULL,
    quantity DECIMAL(19,4) NOT NULL,
    unit_price DECIMAL(19,4) NOT NULL,
    discount_amount DECIMAL(19,4) NOT NULL DEFAULT 0.0000,
    tax_amount DECIMAL(19,4) NOT NULL DEFAULT 0.0000,
    line_total_amount DECIMAL(19,4) NOT NULL DEFAULT 0.0000,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_invoice_line_item PRIMARY KEY (id),
    CONSTRAINT uk_invoice_line_item__invoice_line_number
        UNIQUE (invoice_id, line_number),
    CONSTRAINT chk_invoice_line_item__line_number_positive CHECK (line_number > 0),
    CONSTRAINT chk_invoice_line_item__type_not_blank
        CHECK (CHAR_LENGTH(TRIM(item_type)) > 0),
    CONSTRAINT chk_invoice_line_item__description_not_blank
        CHECK (CHAR_LENGTH(TRIM(description)) > 0),
    CONSTRAINT chk_invoice_line_item__quantity_positive CHECK (quantity > 0),
    CONSTRAINT chk_invoice_line_item__unit_price_nonnegative CHECK (unit_price >= 0),
    CONSTRAINT chk_invoice_line_item__discount_nonnegative CHECK (discount_amount >= 0),
    CONSTRAINT chk_invoice_line_item__tax_nonnegative CHECK (tax_amount >= 0),
    CONSTRAINT chk_invoice_line_item__total_nonnegative CHECK (line_total_amount >= 0),
    CONSTRAINT fk_invoice_line_item__invoice FOREIGN KEY (invoice_id)
        REFERENCES invoice (id) ON DELETE RESTRICT
);

CREATE INDEX idx_invoice_line_item__invoice ON invoice_line_item (invoice_id);

CREATE TABLE payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    payment_number VARCHAR(64) NOT NULL,
    invoice_id BIGINT NOT NULL,
    patient_id BIGINT NOT NULL,
    amount DECIMAL(19,4) NOT NULL,
    currency_code CHAR(3) NOT NULL,
    payment_method VARCHAR(32) NOT NULL,
    payment_reference VARCHAR(256),
    paid_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    recorded_by_user_id BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'RECORDED',
    voided_at TIMESTAMP(6),
    void_reason VARCHAR(512),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_payment PRIMARY KEY (id),
    CONSTRAINT uk_payment__payment_number UNIQUE (payment_number),
    CONSTRAINT chk_payment__number_not_blank CHECK (CHAR_LENGTH(TRIM(payment_number)) > 0),
    CONSTRAINT chk_payment__amount_positive CHECK (amount > 0),
    CONSTRAINT chk_payment__currency_code CHECK (
        CHAR_LENGTH(currency_code) = 3 AND currency_code = UPPER(currency_code)
    ),
    CONSTRAINT chk_payment__method CHECK (
        payment_method IN ('CASH', 'CARD', 'BANK_TRANSFER', 'INSURANCE', 'OTHER')
    ),
    CONSTRAINT chk_payment__status CHECK (status IN ('RECORDED', 'VOIDED')),
    CONSTRAINT chk_payment__void_fields CHECK (
        (status = 'VOIDED' AND voided_at IS NOT NULL AND void_reason IS NOT NULL)
        OR status <> 'VOIDED'
    ),
    CONSTRAINT fk_payment__invoice FOREIGN KEY (invoice_id)
        REFERENCES invoice (id) ON DELETE RESTRICT,
    CONSTRAINT fk_payment__patient FOREIGN KEY (patient_id)
        REFERENCES patient (id) ON DELETE RESTRICT,
    CONSTRAINT fk_payment__recorded_by_user FOREIGN KEY (recorded_by_user_id)
        REFERENCES user_account (id) ON DELETE RESTRICT
);

CREATE INDEX idx_payment__invoice_paid ON payment (invoice_id, paid_at);
CREATE INDEX idx_payment__patient_paid ON payment (patient_id, paid_at);
CREATE INDEX idx_payment__recorded_by_paid ON payment (recorded_by_user_id, paid_at);
CREATE INDEX idx_payment__status ON payment (status);
