CREATE TABLE user_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    username VARCHAR(64) NOT NULL,
    display_name VARCHAR(160),
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    last_login_at TIMESTAMP(6),
    failed_login_count INTEGER NOT NULL DEFAULT 0,
    locked_until TIMESTAMP(6),
    password_changed_at TIMESTAMP(6),
    deleted_at TIMESTAMP(6),
    deleted_by_user_id BIGINT,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_user_id BIGINT,
    updated_by_user_id BIGINT,

    CONSTRAINT pk_user_account
        PRIMARY KEY (id),

    CONSTRAINT uk_user_account__username
        UNIQUE (username),

    CONSTRAINT uk_user_account__email
        UNIQUE (email),

    CONSTRAINT chk_user_account__role
        CHECK (role IN (
            'ADMINISTRATOR',
            'DOCTOR',
            'RECEPTIONIST',
            'PATIENT'
        )),

    CONSTRAINT chk_user_account__status
        CHECK (status IN (
            'ACTIVE',
            'LOCKED',
            'DISABLED',
            'PENDING_RESET'
        )),

    CONSTRAINT chk_user_account__failed_login_count
        CHECK (failed_login_count >= 0),

    CONSTRAINT fk_user_account__deleted_by_user
        FOREIGN KEY (deleted_by_user_id)
        REFERENCES user_account (id)
        ON DELETE SET NULL,

    CONSTRAINT fk_user_account__created_by_user
        FOREIGN KEY (created_by_user_id)
        REFERENCES user_account (id)
        ON DELETE SET NULL,

    CONSTRAINT fk_user_account__updated_by_user
        FOREIGN KEY (updated_by_user_id)
        REFERENCES user_account (id)
        ON DELETE SET NULL
);

CREATE INDEX idx_user_account__status_role
    ON user_account (status, role);

CREATE INDEX idx_user_account__deleted_at
    ON user_account (deleted_at);

CREATE TABLE refresh_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_account_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    revoked_at TIMESTAMP(6),
    revoke_reason VARCHAR(128),
    replaced_by_token_id BIGINT,
    created_ip VARCHAR(45),
    user_agent VARCHAR(512),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_refresh_token
        PRIMARY KEY (id),

    CONSTRAINT uk_refresh_token__token_hash
        UNIQUE (token_hash),

    CONSTRAINT fk_refresh_token__user_account
        FOREIGN KEY (user_account_id)
        REFERENCES user_account (id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_refresh_token__replaced_by_token
        FOREIGN KEY (replaced_by_token_id)
        REFERENCES refresh_token (id)
        ON DELETE SET NULL,

    CONSTRAINT chk_refresh_token__expiry_after_creation
        CHECK (expires_at > created_at)
);

CREATE INDEX idx_refresh_token__user_revoked_expires
    ON refresh_token (user_account_id, revoked_at, expires_at);

CREATE INDEX idx_refresh_token__expires_at
    ON refresh_token (expires_at);

CREATE TABLE password_reset_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_account_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    used_at TIMESTAMP(6),
    requested_ip VARCHAR(45),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_password_reset_token
        PRIMARY KEY (id),

    CONSTRAINT uk_password_reset_token__token_hash
        UNIQUE (token_hash),

    CONSTRAINT fk_password_reset_token__user_account
        FOREIGN KEY (user_account_id)
        REFERENCES user_account (id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_password_reset_token__expiry_after_creation
        CHECK (expires_at > created_at),

    CONSTRAINT chk_password_reset_token__used_after_creation
        CHECK (used_at IS NULL OR used_at >= created_at)
);

CREATE INDEX idx_password_reset_token__user_used_expires
    ON password_reset_token (user_account_id, used_at, expires_at);

CREATE INDEX idx_password_reset_token__expires_at
    ON password_reset_token (expires_at);

CREATE TABLE user_setting (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_account_id BIGINT NOT NULL,
    setting_key VARCHAR(128) NOT NULL,
    setting_value VARCHAR(2048) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_user_setting
        PRIMARY KEY (id),

    CONSTRAINT uk_user_setting__user_setting_key
        UNIQUE (user_account_id, setting_key),

    CONSTRAINT fk_user_setting__user_account
        FOREIGN KEY (user_account_id)
        REFERENCES user_account (id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_user_setting__key_not_blank
        CHECK (CHAR_LENGTH(TRIM(setting_key)) > 0)
);

CREATE INDEX idx_user_setting__user_account
    ON user_setting (user_account_id);

CREATE TABLE system_setting (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    setting_key VARCHAR(128) NOT NULL,
    setting_value VARCHAR(4096) NOT NULL,
    value_type VARCHAR(32) NOT NULL,
    updated_by_user_id BIGINT,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_system_setting
        PRIMARY KEY (id),

    CONSTRAINT uk_system_setting__setting_key
        UNIQUE (setting_key),

    CONSTRAINT fk_system_setting__updated_by_user
        FOREIGN KEY (updated_by_user_id)
        REFERENCES user_account (id)
        ON DELETE SET NULL,

    CONSTRAINT chk_system_setting__value_type
        CHECK (value_type IN (
            'BOOLEAN',
            'INTEGER',
            'DECIMAL',
            'STRING',
            'JSON'
        )),

    CONSTRAINT chk_system_setting__key_not_blank
        CHECK (CHAR_LENGTH(TRIM(setting_key)) > 0)
);

CREATE INDEX idx_system_setting__updated_at
    ON system_setting (updated_at);
